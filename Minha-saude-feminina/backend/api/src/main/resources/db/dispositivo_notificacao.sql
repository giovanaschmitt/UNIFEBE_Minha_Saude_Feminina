-- Aparelhos que recebem notificações push (Firebase Cloud Messaging) (Oracle 19c).
-- Executar uma vez no schema APP_SAUDE_FEMININA.

CREATE TABLE DISPOSITIVO_NOTIFICACAO (
    ID              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    UID_USUARIA     VARCHAR2(512)  NOT NULL,
    TOKEN           VARCHAR2(512)  NOT NULL,
    PLATAFORMA      VARCHAR2(20),
    LEMBRETE_CICLO  NUMBER(1)      DEFAULT 1 NOT NULL,
    CRIADO_EM       TIMESTAMP      NOT NULL,
    ATUALIZADO_EM   TIMESTAMP      NOT NULL,
    CONSTRAINT PK_DISPOSITIVO_NOTIFICACAO PRIMARY KEY (ID),
    CONSTRAINT UK_DISPOSITIVO_TOKEN UNIQUE (TOKEN),
    CONSTRAINT CK_DISPOSITIVO_LEMBRETE CHECK (LEMBRETE_CICLO IN (0, 1))
);

CREATE INDEX IX_DISPOSITIVO_USUARIA ON DISPOSITIVO_NOTIFICACAO (UID_USUARIA);
